"""
Simulated LLM Adapter for FinGuard AI.

This module provides a SIMULATED LLM response generator for demonstration purposes.
It is NOT a real LLM. It generates deterministic template-based responses from
approved demo context and the sanitized input request.

A clean adapter interface allows a real provider to be added later using
server-side environment variables (LLM_PROVIDER, LLM_API_KEY).
"""

import os
from typing import Optional, Dict, Any


class LLMSimulator:
    """
    Deterministic demonstration LLM response simulator.
    Generates template-based responses using approved demo context.
    Clearly labelled as a simulator — not a real LLM.
    """

    RESPONSE_TEMPLATES = {
        "fixed_deposit": (
            "A Fixed Deposit (FD) is a financial instrument offered by banks where you deposit "
            "a lump sum for a fixed period at a predetermined interest rate. Our current FD rate "
            "is 6.5% per annum for a 1-year term. Fixed deposits are generally considered low-risk "
            "investments suitable for conservative investors."
        ),
        "mutual_fund": (
            "Mutual funds pool money from multiple investors to invest in diversified portfolios "
            "of stocks, bonds, or other securities. They are managed by professional fund managers. "
            "Returns vary based on market conditions and fund type. Past performance does not "
            "guarantee future results."
        ),
        "savings_account": (
            "A savings account is a deposit account that earns interest on your balance. "
            "Our current savings account interest rate is 3.5% per annum. Savings accounts "
            "offer high liquidity and are insured up to applicable limits."
        ),
        "general_banking": (
            "Thank you for your banking inquiry. Our bank offers a range of financial products "
            "including savings accounts, fixed deposits, personal loans, and home loans. "
            "For specific product information, please visit our nearest branch or contact "
            "customer support."
        ),
        "transfer": (
            "Fund transfers can be initiated through our banking portal. For security, all "
            "transfers require proper authentication. Please ensure recipient details are "
            "verified before confirming any transaction."
        ),
        "loan": (
            "We offer various loan products including personal loans (starting at 8.9% p.a.) "
            "and home loans (starting at 6.8% p.a.). Loan eligibility depends on income, "
            "credit score, and other factors. Terms and conditions apply."
        ),
    }

    FALLBACK_RESPONSE = (
        "Thank you for your inquiry. I can help with general banking information, "
        "product comparisons, and educational financial content. For personalized "
        "financial advice, please consult a licensed financial advisor."
    )

    @classmethod
    def generate_response(
        cls,
        sanitized_input: str,
        rag_context: str = "",
        approved_facts: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """
        Generates a simulated LLM response based on the sanitized input.
        Returns a dict with the response text and metadata.
        """
        input_lower = sanitized_input.lower()

        # Match input to response templates
        matched_template = None
        matched_key = "general_banking"

        for key, template in cls.RESPONSE_TEMPLATES.items():
            key_terms = key.replace("_", " ").split()
            if any(term in input_lower for term in key_terms):
                matched_template = template
                matched_key = key
                break

        if matched_template is None:
            matched_template = cls.FALLBACK_RESPONSE
            matched_key = "fallback"

        # If RAG context is provided, prepend a note
        response_text = matched_template
        if rag_context:
            response_text = (
                f"Based on available reference documents: {matched_template}"
            )

        return {
            "response": response_text,
            "model": "finguard-simulator-v1",
            "is_simulated": True,
            "matched_topic": matched_key,
            "disclaimer": "This response was generated by a simulated LLM adapter for demonstration purposes only. It is not a real AI model response.",
        }


class LLMAdapter:
    """
    Clean adapter interface for LLM providers.
    Uses LLM_PROVIDER env var to select between simulator and real providers.
    API keys are read from server-side environment variables only.
    """

    def __init__(self):
        self.provider = os.environ.get("LLM_PROVIDER", "simulator")
        self.simulator = LLMSimulator()

    def generate(
        self,
        sanitized_input: str,
        rag_context: str = "",
        approved_facts: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Generate a response using the configured provider."""
        if self.provider == "simulator":
            return self.simulator.generate_response(
                sanitized_input, rag_context, approved_facts
            )
        else:
            # Placeholder for future real LLM provider integration
            # Would use os.environ.get("LLM_API_KEY") for authentication
            # Never expose API keys in frontend code
            return self.simulator.generate_response(
                sanitized_input, rag_context, approved_facts
            )
